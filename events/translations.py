from functools import lru_cache


MACHINE_LANGUAGE_CODES = {
    'en-gb': 'en',
    'zh-hans': 'zh-CN',
}


@lru_cache(maxsize=4096)
def _machine_translate(text, language):
    try:
        from deep_translator import GoogleTranslator
        target = MACHINE_LANGUAGE_CODES.get(language, language)
        return GoogleTranslator(source='auto', target=target).translate(text) or text
    except Exception:
        return text


def translate_text(text, language='en'):
    if not isinstance(text, str) or not text:
        return text

    translations = TRANSLATIONS.get(text, {})
    if not translations:
        return text

    # English is the application's only active interface language.
    if language in ('en', 'en-us', 'en-gb', 'kn', 'kn-in'):
        return text

    if language in translations:
        return translations[language]

    base_language = language.split('-')[0] if '-' in language else None
    if base_language and base_language in translations:
        return translations[base_language]

    translated = translations.get('en')
    if translated:
        return translated

    if language not in ('en', 'en-gb'):
        return _machine_translate(text, language)

    return text


